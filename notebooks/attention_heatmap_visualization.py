"""
Attention Weight Visualization for Attentive Probes
====================================================

This script extracts and visualizes the spatial attention weights generated by the
attentive probe (cross-attention layer). The attention weights show which regions
of the video the probe prioritizes when making predictions.

Key steps:
1. Load the pretrained encoder and attentive probe checkpoint
2. Extract 1D spatial attention weights via forward hooks
3. Reshape to 3D spatiotemporal grid (T, H, W)
4. Upsample to original video resolution
5. Create heatmap overlays for each frame
6. Save as MP4 video or sequence of PNG frames

Requirements:
- torch
- opencv-python (cv2)
- imageio (for video writing)
- numpy
- matplotlib
- yaml
"""

